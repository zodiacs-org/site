const lower = (text: string) => text.charAt(0).toLowerCase() + text.slice(1);
/** The article each sign takes: le Bélier, la Vierge, les Gémeaux. */
const ARTICLE: Record<string, 'le' | 'la' | 'les'> = {
  aries: 'le', taurus: 'le', gemini: 'les', cancer: 'le', leo: 'le', virgo: 'la',
  libra: 'la', scorpio: 'le', sagittarius: 'le', capricorn: 'le', aquarius: 'le', pisces: 'les',
};
const SLUG_BY_NAME = new Map(SIGNS.map((sign) => [signName(sign, 'fr'), sign.slug]));
const articleOf = (sign: string) => ARTICLE[SLUG_BY_NAME.get(sign) ?? ''] ?? 'le';
/** "le Bélier", "la Vierge", "les Gémeaux". */
const the = (sign: string) => `${articleOf(sign)} ${sign}`;
/** "du Bélier", "de la Vierge", "des Gémeaux". */
const of = (sign: string) => ({ le: `du ${sign}`, la: `de la ${sign}`, les: `des ${sign}` })[articleOf(sign)];
const RULED: Record<string, string> = { Sun: 'Gouverné par le', Moon: 'Gouverné par la' };

