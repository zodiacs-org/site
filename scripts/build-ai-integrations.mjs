/** Reproducible bundles; dependencies remain external, pinned and inspectable. */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { buildChartStudio } from './build-chart-studio.mjs';
import { addAiLifetimeBoundary } from './ai-runtime-lifetime.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
await buildChartStudio(check);
const outputs = [
  ['src/ai-tools/http.ts', 'api/_ai/runtime.mjs', ['@modelcontextprotocol/server', '@modelcontextprotocol/core', 'zod', '@vercel/firewall', '@supabase/supabase-js']],
  ['src/ai-tools/local.ts', 'plugins/zodiacs-developer/mcp/server.mjs', ['@modelcontextprotocol/server', '@modelcontextprotocol/core', 'zod']],
  ['src/ai-tools/watch/runtime.ts', 'integrations/generated/sky-watch.mjs', ['@modelcontextprotocol/server', '@modelcontextprotocol/core', 'zod', '@vercel/firewall', '@supabase/supabase-js']],
];
for (const [entry, output, external] of outputs) {
  const result = await build({ absWorkingDir: root, entryPoints: [entry], bundle: true, platform: 'node', target: 'node22', format: 'esm', write: false, external, legalComments: 'inline', banner: { js: '// Generated by scripts/build-ai-integrations.mjs. Do not edit.\n// Site-derived adapter: all rights reserved. Dependencies retain their licenses.' } });
  const bytes = Buffer.from(addAiLifetimeBoundary(result.outputFiles[0].text, entry.endsWith('/local.ts')));
  const path = resolve(root, output);
  if (check) {
    const current = await readFile(path).catch(() => null);
    if (!current?.equals(bytes)) throw new Error(`${output} is stale; run npm run ai:build`);
  } else { await mkdir(dirname(path), { recursive: true }); await writeFile(path, bytes); }
  console.log(`${check ? 'Verified' : 'Built'} ${output} (${bytes.length} bytes)`);
}
// The current portable format and older Codex clients share one metadata source.
const compatibility = JSON.parse(await readFile(resolve(root, 'plugins/zodiacs-developer/.codex-plugin/plugin.json'), 'utf8'));
const portable = Object.fromEntries(['name', 'version', 'description', 'author', 'homepage', 'repository', 'license', 'keywords'].map(key => [key, compatibility[key]]));
portable.$schema = 'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json';
portable.extensions = { 'com.openai': { ...compatibility.extensions?.['com.openai'], interface: compatibility.interface } };
const portableMcp = { $schema: 'https://agent-plugins.org/schemas/1.0.0/mcp.schema.json', mcpServers: { 'zodiacs-developer': { type: 'stdio', command: 'node', cwd: './', args: ['${PLUGIN_ROOT}/mcp/server.mjs'] } } };
for (const [output, data] of [['plugins/zodiacs-developer/plugin.json', portable], ['plugins/zodiacs-developer/mcp.json', portableMcp]]) {
  const bytes = Buffer.from(JSON.stringify(data, null, 2) + '\n');
  if (check) { if (!bytes.equals(await readFile(resolve(root, output)))) throw new Error(`${output} is stale; run npm run ai:build`); }
  else await writeFile(resolve(root, output), bytes);
  console.log(`${check ? 'Verified' : 'Built'} ${output}`);
}
// Sky's portable manifest is authoritative; also package the compatibility files
// read by current local-marketplace clients so upgrades retain version and MCP.
const sky = JSON.parse(await readFile(resolve(root, 'plugins/zodiacs-sky/plugin.json'), 'utf8'));
const skyCompatibility = Object.fromEntries(['name', 'version', 'description', 'author', 'homepage', 'repository', 'license', 'keywords'].map(key => [key, sky[key]]));
const { interface: skyInterface, ...skySettings } = sky.extensions['com.openai'];
Object.assign(skyCompatibility, { skills: './skills/', mcpServers: './.mcp.json', interface: skyInterface });
skyCompatibility.extensions = { 'com.openai': skySettings };
const skyMcp = { mcpServers: { 'zodiacs-sky': { url: 'https://zodiacs.org/mcp' } } };
for (const [output, data] of [['plugins/zodiacs-sky/.codex-plugin/plugin.json', skyCompatibility], ['plugins/zodiacs-sky/.mcp.json', skyMcp]]) {
  const bytes = Buffer.from(JSON.stringify(data, null, 2) + '\n');
  const path = resolve(root, output);
  if (check) { if (!bytes.equals(await readFile(path))) throw new Error(`${output} is stale; run npm run ai:build`); }
  else { await mkdir(dirname(path), { recursive: true }); await writeFile(path, bytes); }
  console.log(`${check ? 'Verified' : 'Built'} ${output}`);
}
