/** Reproducible bundles; dependencies remain external, pinned and inspectable. */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { buildSkyCalendar } from './build-sky-calendar.mjs';
import { buildChartStudio } from './build-chart-studio.mjs';
import { buildHoroscopePanel } from './build-horoscope-panel.mjs';
import { buildOccasionsPanel } from './build-occasions-panel.mjs';
import { buildAccountsConsent } from './build-accounts-consent.mjs';
import { peopleIndexCurrent, renderFromDisk, STALE_MESSAGE } from './build-ai-people.mjs';
import { addAiLifetimeBoundary } from './ai-runtime-lifetime.mjs';
import { syncPanelFingerprints } from './panel-fingerprints.mjs';
import { buildPluginAvatar } from './build-plugin-avatar.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
await buildPluginAvatar(check);
const panelHtml = {
  'sky-events': await buildSkyCalendar(check),
  'chart-studio': await buildChartStudio(check),
  horoscopes: await buildHoroscopePanel(check),
  occasions: await buildOccasionsPanel(check),
};
await syncPanelFingerprints(panelHtml, check);
// The account consent page; the hosted function serves it only while ZODIACS_ACCOUNTS_ENABLED=1.
await buildAccountsConsent(check);
// The famous-people tools read a compact index of the people the site publishes (scripts/build-ai-people.mjs).
if (check) { if (!(await peopleIndexCurrent())) throw new Error(STALE_MESSAGE); }
else await writeFile(new URL('../src/ai-tools/features/people-index.json', import.meta.url), await renderFromDisk());
const outputs = [
  ['src/ai-tools/http.ts', 'api/_ai/runtime.mjs', ['@modelcontextprotocol/server', '@modelcontextprotocol/core', 'zod', '@vercel/firewall', '@supabase/supabase-js']],
  ['src/ai-tools/local.ts', 'plugins/zodiacs-developer/mcp/server.mjs', ['@modelcontextprotocol/server', '@modelcontextprotocol/core', 'zod']],
  ['src/ai-tools/watch/runtime.ts', 'integrations/generated/sky-watch.mjs', ['@modelcontextprotocol/server', '@modelcontextprotocol/core', 'zod', '@vercel/firewall', '@supabase/supabase-js']],
];
// The AI runtimes never compute a birth-time window. src/lib/engine/full.ts
// (reached through the occasion tools' returns) loads that engine module on
// demand; bundled, its shared chunk would turn the engine's module state into
// lazily initialised wrappers that the lifetime review cannot clear. An empty
// stand-in keeps the engine's state top-level, where clearAiEngineState resets it.
const noBirthWindow = {
  name: 'ai-no-birth-window',
  setup(builder) {
    builder.onResolve({ filter: /^@zodiacs\/engine\/window$/ }, () => ({ path: 'birth-window', namespace: 'ai-no-birth-window' }));
    builder.onLoad({ filter: /.*/, namespace: 'ai-no-birth-window' }, () => ({ contents: "export function birthWindow() { throw new Error('Birth-time windows are not part of the AI runtime.'); }", loader: 'js' }));
  },
};
// The runtimes are Node servers. Shared modules ask Vite's import.meta.env.SSR
// which half they run in (the Russian copy reads its data on the server and a
// page's serialized payload in the browser); outside Vite, import.meta.env is
// undefined, so a Russian answer threw and came back as calculation-failed.
const serverDefines = { 'import.meta.env.SSR': 'true' };
for (const [entry, output, external] of outputs) {
  const result = await build({ absWorkingDir: root, entryPoints: [entry], bundle: true, platform: 'node', target: 'node22', format: 'esm', write: false, external, define: serverDefines, plugins: [noBirthWindow], legalComments: 'inline', banner: { js: '// Generated by scripts/build-ai-integrations.mjs. Do not edit.\n// Site-derived adapter: all rights reserved. Dependencies retain their licenses.' } });
  const bytes = Buffer.from(addAiLifetimeBoundary(result.outputFiles[0].text, entry.endsWith('/local.ts')));
  const path = resolve(root, output);
  if (check) {
    const current = await readFile(path).catch(() => null);
    if (!current?.equals(bytes)) throw new Error(`${output} is stale; run npm run ai:build`);
  } else { await mkdir(dirname(path), { recursive: true }); await writeFile(path, bytes); }
  console.log(`${check ? 'Verified' : 'Built'} ${output} (${bytes.length} bytes)`);
}
// The current portable format and older Codex clients share one metadata source.
const compatibility = JSON.parse(await readFile(resolve(root, 'plugins/zodiacs-developer/.codex-plugin/plugin.json'), 'utf8'));
const portable = Object.fromEntries(['name', 'version', 'description', 'author', 'homepage', 'repository', 'license', 'keywords'].map(key => [key, compatibility[key]]));
portable.$schema = 'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json';
portable.extensions = { 'com.openai': { ...compatibility.extensions?.['com.openai'], interface: compatibility.interface } };
const portableMcp = { $schema: 'https://agent-plugins.org/schemas/1.0.0/mcp.schema.json', mcpServers: { 'zodiacs-developer': { type: 'stdio', command: 'node', cwd: './', args: ['${PLUGIN_ROOT}/mcp/server.mjs'] } } };
for (const [output, data] of [['plugins/zodiacs-developer/plugin.json', portable], ['plugins/zodiacs-developer/mcp.json', portableMcp]]) {
  const bytes = Buffer.from(JSON.stringify(data, null, 2) + '\n');
  if (check) { if (!bytes.equals(await readFile(resolve(root, output)))) throw new Error(`${output} is stale; run npm run ai:build`); }
  else await writeFile(resolve(root, output), bytes);
  console.log(`${check ? 'Verified' : 'Built'} ${output}`);
}
// Sky's portable manifest is authoritative; also package the compatibility files
// read by current local-marketplace clients so upgrades retain version and MCP.
const sky = JSON.parse(await readFile(resolve(root, 'plugins/zodiacs-sky/plugin.json'), 'utf8'));
const skyCompatibility = Object.fromEntries(['name', 'version', 'description', 'author', 'homepage', 'repository', 'license', 'keywords'].map(key => [key, sky[key]]));
const { interface: skyInterface, ...skySettings } = sky.extensions['com.openai'];
Object.assign(skyCompatibility, { skills: './skills/', mcpServers: './.mcp.json', interface: skyInterface });
skyCompatibility.extensions = { 'com.openai': skySettings };
// Claude requires an explicit remote transport in the shared MCP configuration.
const skyMcp = { mcpServers: { 'zodiacs-sky': { type: 'http', url: 'https://zodiacs.org/mcp' } } };
const skyClaude = Object.fromEntries(['name', 'version', 'description', 'author', 'homepage', 'repository', 'license', 'keywords'].map(key => [key, sky[key]]));
Object.assign(skyClaude, {
  displayName: skyInterface.displayName,
  mcpServers: './.mcp.json',
  icon: skyInterface.logo,
  documentationUrl: sky.homepage,
  supportUrl: skyInterface.supportURL,
  privacyPolicyUrl: skyInterface.privacyPolicyURL,
  termsOfServiceUrl: skyInterface.termsOfServiceURL,
});
for (const [output, data] of [['plugins/zodiacs-sky/.codex-plugin/plugin.json', skyCompatibility], ['plugins/zodiacs-sky/.mcp.json', skyMcp], ['plugins/zodiacs-sky/.claude-plugin/plugin.json', skyClaude]]) {
  const bytes = Buffer.from(JSON.stringify(data, null, 2) + '\n');
  const path = resolve(root, output);
  if (check) { if (!bytes.equals(await readFile(path))) throw new Error(`${output} is stale; run npm run ai:build`); }
  else { await mkdir(dirname(path), { recursive: true }); await writeFile(path, bytes); }
  console.log(`${check ? 'Verified' : 'Built'} ${output}`);
}
