/** Bundle the calendar with the same inline sign assets used by the other panels. */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('../', import.meta.url);

export async function buildSkyCalendar(check = false) {
  const source = await readFile(new URL('src/lib/signs.ts', root), 'utf8');
  const signs = [...source.matchAll(/\{ slug: '([a-z]+)', name:/gu)].map(([, slug]) => slug);
  if (signs.length !== 12) throw new Error('Expected the twelve canonical signs');
  const icons = Object.fromEntries(await Promise.all(signs.map(async slug => [slug, 'data:image/webp;base64,' + (await readFile(new URL(`public/assets/zodiac-icons/128/${slug}.webp`, root))).toString('base64')])));
  const bundle = await build({ absWorkingDir: fileURLToPath(root), entryPoints: ['src/ai-tools/widget.ts'], bundle: true, write: false, format: 'esm', platform: 'node', target: 'node22' });
  const { renderSkyCalendar } = await import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].text).toString('base64'));
  const html = renderSkyCalendar(icons);
  if (Buffer.byteLength(html) > 300_000) throw new Error('The sky calendar exceeds its 300 KB resource budget');
  const content = '// Generated by scripts/build-sky-calendar.mjs via ai:build. Do not edit.\nexport const WIDGET_HTML = ' + JSON.stringify(html) + ';\n';
  const output = new URL('integrations/generated/sky-calendar.mjs', root);
  if (check) {
    if (await readFile(output, 'utf8').catch(() => '') !== content) throw new Error('The sky calendar is stale; run ai:build');
  } else {
    await mkdir(new URL('integrations/generated/', root), { recursive: true });
    await writeFile(output, content);
  }
  console.log(`${check ? 'Verified' : 'Built'} the sky calendar (${Buffer.byteLength(html)} bytes, self-contained)`);
  return html;
}
