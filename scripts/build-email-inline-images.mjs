/**
 * Embeds the brand ring and the twelve pastel sign discs for emails that
 * must load nothing remote (the confirmation email). They travel as inline
 * attachments referenced by cid:, so opening the message fetches nothing.
 *
 * Run: node scripts/build-email-inline-images.mjs [--check]
 * Writes src/lib/email/inline-images.ts from the committed PNGs.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BRAND_ICON_PATHS } from '../src/lib/brand-icons.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(root, 'src/lib/email/inline-images.ts');
const SIGNS = ['aries', 'taurus', 'gemini', 'cancer', 'leo', 'virgo', 'libra', 'scorpio',
  'sagittarius', 'capricorn', 'aquarius', 'pisces'];

const base64 = async (publicPath) => (await readFile(resolve(root, 'public', publicPath.replace(/^\//u, '')))).toString('base64');

export async function renderInlineImages() {
  const ring = await base64(BRAND_ICON_PATHS.favicon);
  const signs = [];
  for (const sign of SIGNS) signs.push(`  ${sign}: '${await base64(`/assets/zodiac-icons/128/${sign}.png`)}',`);
  return `// Generated by scripts/build-email-inline-images.mjs — do not edit.
// Base64 PNGs: ${BRAND_ICON_PATHS.favicon} and /assets/zodiac-icons/128/{sign}.png.

export const RING_PNG_BASE64 = '${ring}';

export const SIGN_PNG_BASE64: Readonly<Record<string, string>> = {
${signs.join('\n')}
};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = await renderInlineImages();
  if (process.argv.includes('--check')) {
    const current = await readFile(OUT, 'utf8').catch(() => '');
    if (current !== next) {
      console.error('email-inline-images: src/lib/email/inline-images.ts is stale; run node scripts/build-email-inline-images.mjs');
      process.exit(1);
    }
    console.log('email-inline-images: up to date');
  } else {
    await writeFile(OUT, next);
    console.log(`email-inline-images: wrote ${OUT}`);
  }
}
