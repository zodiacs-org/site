/*
 * The People pages' degrees, to six decimals, for rounding once.
 *
 *   node scripts/build-people-degrees.mjs           →  src/data/people-degrees.json
 *   node scripts/build-people-degrees.mjs --check   (fails on drift)
 *
 * src/data/people.json and the released copy store each placement's degree
 * to 0.01°, and the copy prints that stored value to 0.1°, so a body at
 * 28.245° Leo reads 28.3°. This recomputes each placement at the record's own
 * noon instant (computation.utcInstant) the way the pilot computed it
 * (docs/phase5/people-pilot/tools/compute-astro.mjs: GeoVector rotated by
 * Rotation_EQJ_ECT), checks that it reproduces every stored 0.01° value, and
 * writes the full degree in sign. The page (src/lib/people-degrees.ts) prints
 * that full value to 0.1°. people.json and the frozen copy are not touched.
 */
import './lib/deltat-install.mjs';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const Astronomy = require('astronomy-engine');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'src/data/people.json');
const out = resolve(root, 'src/data/people-degrees.json');
const CHECK = process.argv.includes('--check');

const norm = (value) => ((value % 360) + 360) % 360;
function longitudeOf(body, date) {
  const time = Astronomy.MakeTime(date);
  const equatorial = Astronomy.GeoVector(Astronomy.Body[body], time, true);
  const ecliptic = Astronomy.RotateVector(Astronomy.Rotation_EQJ_ECT(time), equatorial);
  return norm((Math.atan2(ecliptic.y, ecliptic.x) * 180) / Math.PI);
}

const { people } = JSON.parse(await readFile(source, 'utf8'));
const degrees = {};
const problems = [];
for (const person of [...people].sort((a, b) => a.slug.localeCompare(b.slug))) {
  const at = new Date(person.computation.utcInstant);
  const row = {};
  for (const placement of person.placements) {
    const degree = longitudeOf(placement.body, at) % 30;
    if (Number(degree.toFixed(2)) !== placement.degree) {
      problems.push(`${person.slug} ${placement.body}: ${degree} does not reproduce ${placement.degree}`);
    }
    row[placement.body] = Number(degree.toFixed(6));
  }
  degrees[person.slug] = row;
}
if (problems.length) {
  console.error('✗ people degrees do not reproduce people.json:');
  for (const problem of problems.slice(0, 20)) console.error('  -', problem);
  process.exit(1);
}

const text = `${JSON.stringify({
  note: 'Degree in sign at each record\'s noon instant, to six decimals, so the People pages round once. Generated by scripts/build-people-degrees.mjs from src/data/people.json.',
  people: degrees,
}, null, 1)}\n`;
if (CHECK) {
  const current = await readFile(out, 'utf8').catch(() => '');
  if (current !== text) {
    console.error('✗ src/data/people-degrees.json is stale; run node scripts/build-people-degrees.mjs');
    process.exit(1);
  }
  console.log(`✓ src/data/people-degrees.json is current (${Object.keys(degrees).length} people)`);
} else {
  await writeFile(out, text);
  console.log(`✓ src/data/people-degrees.json: ${Object.keys(degrees).length} people`);
}
