/**
 * Bundles the hosted MCP endpoint (https://zodiacs.org/mcp) for the shared
 * Vercel function.
 *
 *   node scripts/build-mcp-remote.mjs           # write api/_mcp/remote.mjs
 *   node scripts/build-mcp-remote.mjs --check   # fail on drift (tests/api/mcp-remote-bundle.test.ts)
 *
 * The same discipline as the compute API's bundle (scripts/build-compute-handler.mjs):
 *
 * - The engine and astronomy-engine's ESM build are inlined, with the MCP SDK
 *   and zod, so nothing is resolved at run time but Node's own modules and
 *   `@vercel/firewall`. The build asserts that.
 * - The engine files it carries must be exactly the ones whose private mutable
 *   state was audited for the compute API's bundle: the same reviewed-input
 *   digest, PRIVACY_REVIEWED_ENGINE_INPUTS_SHA256. A different set fails the
 *   build until it is audited.
 * - The exported factory is wrapped so that, when each request completes, the
 *   engine's exact-TT frame, its Pluto segments and its Moon counter are
 *   cleared, as they are after a compute API request.
 * - The MCP SDK's JSON Schema validator is its server-runtime one
 *   (@cfworker/json-schema), which validates without generating code, rather
 *   than its Node default, Ajv, which compiles schemas with `new Function`. The
 *   site's audits follow every code path a function can run
 *   (src/lib/share-positions-callers.test.ts), and generated code is a path
 *   they cannot follow. The tools' own schemas are zod's, so nothing they
 *   validate changes.
 *
 * Source: src/mcp/hosted-entry.ts. Output: api/_mcp/remote.mjs and its
 * declarations, remote.d.mts. The leading underscore keeps Vercel from
 * deploying the directory as functions.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';
import * as esbuild from 'esbuild';
import { runtimeImports } from './build-compute-local-time.mjs';
import {
  ALLOWED_RUNTIME_IMPORTS, PRIVACY_REVIEWED_ENGINE_INPUTS_SHA256, externalImports,
} from './build-compute-handler.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const ENTRY = resolve(ROOT, 'src/mcp/hosted-entry.ts');
/** The SDK's server-runtime shim: its validator generates no code (see the header). */
const EVAL_FREE_SHIM = resolve(ROOT, 'node_modules/@modelcontextprotocol/server/dist/shimsWorkerd.mjs');
const evalFreeShim = {
  name: 'mcp-eval-free-json-schema-validator',
  setup(build) {
    build.onResolve({ filter: /^@modelcontextprotocol\/server\/_shims$/ }, () => ({ path: EVAL_FREE_SHIM }));
  },
};
export const BUNDLE_PATH = 'api/_mcp/remote.mjs';
export const TYPES_PATH = 'api/_mcp/remote.d.mts';

const TYPES = `// Generated by scripts/build-mcp-remote.mjs. Do not edit.
// Declarations for the bundle beside this file; the source is src/mcp/hosted-http.ts.
export { createHostedMcpHandler } from '../../src/mcp/hosted-http.js';
`;

async function packageVersion(name) {
  const text = await readFile(resolve(ROOT, 'node_modules', name, 'package.json'), 'utf8');
  return JSON.parse(text).version;
}

/** Fail closed if the audited engine memos are not exactly the ones this bundle carries. */
export function addMcpLifetimeBoundary(generated) {
  const exportBlock = 'export {\n  createHostedMcpHandler\n};';
  for (const marker of [
    'var last;',
    'var last;\nfunction eclipticFrame(tt) {',
    '  last = {\n    tt,\n    rows: [',
    'var pluto_cache = [];',
    'var CalcMoonCount = 0;',
    exportBlock,
  ]) {
    if (generated.split(marker).length !== 2) throw new Error(`hosted MCP private state changed; review cleanup: ${marker}`);
  }
  if (/\b(?:cache_e_tilt|sidereal_time_cache)\b|\bvar last\d+\b/u.test(generated)) {
    throw new Error('another time cache is now bundled; review private-state cleanup');
  }
  return generated.replace(exportBlock, 'export {\n  createStatelessHostedMcpHandler as createHostedMcpHandler\n};') + `
// Server-only lifetime boundary, the compute API's (scripts/build-compute-handler.mjs):
// when a request completes, including refusals and exceptions, the engine's
// exact-TT frame, its epoch-selected Pluto segments and its aggregate Moon
// counter are cleared. Calculations are synchronous, so clearing them cannot
// interrupt one.
function createStatelessHostedMcpHandler(options) {
  const handler = createHostedMcpHandler(options);
  return async function statelessHostedMcpHandler(req, res) {
    try {
      return await handler(req, res);
    } finally {
      last = undefined;
      pluto_cache.length = 0;
      CalcMoonCount = 0;
    }
  };
}
`;
}

export async function buildMcpRemoteBundle() {
  const engine = await packageVersion('@zodiacs/engine');
  const astronomy = await packageVersion('astronomy-engine');
  const sdk = await packageVersion('@modelcontextprotocol/server');
  const zod = await packageVersion('zod');
  const banner = [
    '// Generated by scripts/build-mcp-remote.mjs from src/mcp/hosted-http.ts. Do not edit.',
    '//',
    '// The hosted MCP endpoint for the shared Vercel function, with its dependencies inlined:',
    `// @zodiacs/engine ${engine} (MIT; its ΔT values are CC BY 4.0, attributed in vendor/README.md),`,
    `// astronomy-engine ${astronomy} (MIT, Copyright (c) 2019-2023 Don Cross),`,
    `// @modelcontextprotocol/server ${sdk} (MIT) and zod ${zod} (MIT).`,
    `// Bundled by esbuild ${esbuild.version}, platform node, format esm, target node22.`,
  ].join('\n');
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    absWorkingDir: ROOT,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    external: ALLOWED_RUNTIME_IMPORTS,
    banner: { js: banner },
    legalComments: 'inline',
    sourcemap: false,
    minify: false,
    write: false,
    metafile: true,
    plugins: [evalFreeShim],
  });
  const [file] = result.outputFiles;
  const text = addMcpLifetimeBoundary(file.text);
  const inputs = Object.keys(result.metafile.inputs).sort();
  const reviewedInputs = inputs.filter((input) => /^node_modules\/(?:@zodiacs\/engine|astronomy-engine)\//u.test(input)
    || input === 'src/lib/engine/time-basis.mjs');
  const reviewedHash = createHash('sha256');
  for (const input of reviewedInputs) {
    reviewedHash.update(input).update('\0').update(await readFile(resolve(ROOT, input))).update('\0');
  }
  const problems = [];
  if (reviewedHash.digest('hex') !== PRIVACY_REVIEWED_ENGINE_INPUTS_SHA256) {
    problems.push('the engine inputs differ from the ones audited for the compute API; audit their private mutable state first');
  }
  for (const needed of ['src/mcp/hosted-http.ts', 'src/mcp/hosted-server.ts', 'src/lib/compute-api/endpoints.ts']) {
    if (!inputs.includes(needed)) problems.push(`the bundle is missing ${needed}`);
  }
  if (inputs.some((input) => /(?:^|\/)ajv(?:Provider[^/]*)?(?:\/|\.)/u.test(input))) {
    problems.push('the bundle carries Ajv, which generates code at run time');
  }
  if (/\bnew Function\s*\(|(?<![.\w])eval\s*\(/u.test(text.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/gu, ''))) {
    problems.push('the bundle generates code at run time (new Function or eval)');
  }
  for (const excluded of ['src/mcp/server.ts', 'src/mcp/create-server.ts']) {
    if (inputs.includes(excluded)) problems.push(`the bundle carries ${excluded}, the local adapter's transport`);
  }
  const external = externalImports(text);
  const unexpected = external.filter((specifier) => !ALLOWED_RUNTIME_IMPORTS.includes(specifier));
  if (unexpected.length) {
    problems.push(`the bundle loads ${unexpected.join(', ')} at run time; only Node's modules and ${ALLOWED_RUNTIME_IMPORTS.join(', ')} may stay external`);
  }
  if (runtimeImports(text).some((entry) => !entry.startsWith('import '))) {
    problems.push('the bundle calls import() or require() at run time');
  }
  if (problems.length) throw new Error(`build-mcp-remote: ${problems.join('; ')}`);
  return { bytes: Buffer.from(text), types: Buffer.from(TYPES, 'utf8'), inputs, external };
}

const invokedDirectly = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;
if (invokedDirectly) {
  const check = process.argv.includes('--check');
  const { bytes, types, inputs } = await buildMcpRemoteBundle();
  const digest = createHash('sha256').update(bytes).digest('hex');
  if (check) {
    const stale = [];
    for (const [path, expected] of [[BUNDLE_PATH, bytes], [TYPES_PATH, types]]) {
      const current = await readFile(resolve(ROOT, path)).catch(() => null);
      if (current === null || !current.equals(expected)) stale.push(path);
    }
    if (stale.length) {
      console.error(`build-mcp-remote: ${stale.join(', ')} ${stale.length === 1 ? 'is' : 'are'} stale;`
        + ' run node scripts/build-mcp-remote.mjs and commit the result');
      process.exit(1);
    }
    console.log(`build-mcp-remote: up to date (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…)`);
  } else {
    await mkdir(dirname(resolve(ROOT, BUNDLE_PATH)), { recursive: true });
    await writeFile(resolve(ROOT, BUNDLE_PATH), bytes);
    await writeFile(resolve(ROOT, TYPES_PATH), types);
    console.log(`build-mcp-remote: wrote ${BUNDLE_PATH} (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…, ${inputs.length} inputs)`);
  }
}
