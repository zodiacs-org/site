/**
 * Bundles the local MCP adapter into the runnable artifact the example ships.
 *
 *   node scripts/build-mcp-server.mjs            # write examples/mcp-server/server.mjs
 *   node scripts/build-mcp-server.mjs --check    # fail on drift (CI)
 *
 * The adapter's source is `src/mcp/`, which imports the site's real engine and
 * its real `src/lib/compare/` comparison. Those are TypeScript and unpublished,
 * so the artifact is a bundle rather than a package with dependencies on them:
 * that is what keeps the comparison rules in one place instead of copied into
 * a second repository.
 *
 * The three published dependencies stay external and pinned. Inlining the MCP
 * SDK would bury the one part of this artifact a reviewer most needs to check
 * against npm.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import * as esbuild from 'esbuild';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const ENTRY = resolve(ROOT, 'src/mcp/server.ts');
const OUT = resolve(ROOT, 'examples/mcp-server/server.mjs');

/** Kept external: each is a real, published, pinned npm dependency. */
export const EXTERNAL = Object.freeze([
  '@modelcontextprotocol/server',
  '@modelcontextprotocol/core',
  'zod',
]);

/**
 * Every JSON table as one string literal, parsed at its first import, as
 * scripts/build-compute-local-time.mjs inlines them: the zone names
 * resolve_birth_time loads on demand, which esbuild would otherwise wrap in
 * a CommonJS shim, and the place index search_places reads. V8 parses JSON
 * text faster than the same data as code.
 */
const jsonAsText = {
  name: 'json-as-text',
  setup(build) {
    // esbuild takes Go regular expressions: no u flag.
    build.onLoad({ filter: /\.json$/ }, async (args) => {
      const text = JSON.stringify(JSON.parse(await readFile(args.path, 'utf8')));
      return { contents: `export default JSON.parse(${JSON.stringify(text)});\n`, loader: 'js' };
    });
  },
};

const version = async (name) => JSON.parse(
  await readFile(resolve(ROOT, 'node_modules', name, 'package.json'), 'utf8'),
).version;

export async function buildServerBundle() {
  const [engine, sdk, zod, adapter] = await Promise.all([
    version('@zodiacs/engine'),
    version('@modelcontextprotocol/server'),
    version('zod'),
    readFile(resolve(ROOT, 'src/mcp/bounds.ts'), 'utf8')
      .then((source) => /ADAPTER_VERSION = '([^']+)'/.exec(source)?.[1]),
  ]);
  if (!adapter) throw new Error('could not read ADAPTER_VERSION from src/mcp/bounds.ts');

  const banner = [
    '// Generated by scripts/build-mcp-server.mjs from src/mcp/server.ts. Do not edit.',
    '//',
    `// zodiacs-mcp-server ${adapter} — a local stdio MCP server. Run: node server.mjs`,
    `// Bundles @zodiacs/engine ${engine} and the site's src/lib/compare/ comparison.`,
    `// External, pinned: @modelcontextprotocol/server ${sdk}, zod ${zod}.`,
    `// Bundled by esbuild ${esbuild.version}, platform node, format esm, target node22.`,
    '//',
    '// Reads stdin, writes protocol messages to stdout and nothing else there.',
    '// Opens no listener, binds no port, makes no outbound request, touches no file.',
  ].join('\n');

  const result = await esbuild.build({
    entryPoints: [ENTRY],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    external: [...EXTERNAL],
    banner: { js: banner },
    legalComments: 'inline',
    sourcemap: false,
    minify: false,
    write: false,
    plugins: [jsonAsText],
  });
  const [file] = result.outputFiles;
  return { bytes: Buffer.from(file.contents), versions: { adapter, engine, sdk, zod, esbuild: esbuild.version } };
}

// Importable without side effects: the drives that run against the artifact
// import `buildServerBundle` to detect a stale one, and a guard that rebuilt
// it on import would hide exactly what it is there to catch.
const invokedDirectly = process.argv[1]
  && pathToFileURL(process.argv[1]).href === import.meta.url;
if (!invokedDirectly) {
  // Nothing else to do on import.
} else {
const check = process.argv.includes('--check');
const { bytes, versions } = await buildServerBundle();
const digest = createHash('sha256').update(bytes).digest('hex');

if (check) {
  const current = await readFile(OUT).catch(() => null);
  if (current === null) {
    console.error(`build-mcp-server: ${OUT} is missing; run node scripts/build-mcp-server.mjs`);
    process.exit(1);
  }
  if (!current.equals(bytes)) {
    console.error('build-mcp-server: examples/mcp-server/server.mjs is stale;'
      + ' run node scripts/build-mcp-server.mjs and commit the result');
    process.exit(1);
  }
  console.log(`build-mcp-server: up to date (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…)`);
} else {
  await writeFile(OUT, bytes);
  console.log(`build-mcp-server: wrote examples/mcp-server/server.mjs`
    + ` (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…)`);
  console.log(`  adapter ${versions.adapter}, engine ${versions.engine},`
    + ` sdk ${versions.sdk}, zod ${versions.zod}, esbuild ${versions.esbuild}`);
}
}
