/**
 * Bundles the site's local-time resolver for the compute API's function.
 *
 *   node scripts/build-compute-local-time.mjs           # write api/_compute/local-time.mjs
 *   node scripts/build-compute-local-time.mjs --check   # fail on drift (CI)
 *
 * src/lib/time/localToUtc.ts is what the birth chart calculator resolves a
 * local time with. Node cannot load it in a Vercel function as it stands: its
 * relative imports have no extension, and it loads its tables (the local mean
 * time eras and the pinned zone history before 1970) as JSON without import
 * attributes. esbuild resolves both, so the function runs the same source
 * rather than a second implementation, with every table inlined. The bundle
 * imports nothing at run time, which the build asserts.
 *
 * Each table is inlined as one JSON string, parsed when it is first imported,
 * rather than as an object literal. The tables are nearly all of the bundle's
 * bytes: as literals they were some 41,000 of its 49,732 syntax nodes, which
 * every tool parsing the repository's sources paid for (the import-graph tests
 * read api/), and V8 parses JSON text faster than the same data as code.
 *
 * Source: src/lib/compute-api/local-time-source.ts. Output:
 * api/_compute/local-time.mjs and its declarations, local-time.d.mts. The
 * leading underscore keeps Vercel from deploying the directory as functions.
 */
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';
import * as esbuild from 'esbuild';
import ts from 'typescript';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const ENTRY = resolve(ROOT, 'src/lib/compute-api/local-time-source.ts');
export const BUNDLE_PATH = 'api/_compute/local-time.mjs';
export const TYPES_PATH = 'api/_compute/local-time.d.mts';

const TYPES = `// Generated by scripts/build-compute-local-time.mjs. Do not edit.
// Each call owns its resolver caches; a completed request must dispose them.
import type { LocalTimeModule } from '../../src/lib/compute-api/local-time.js';
export declare function createLocalTimeModule(): LocalTimeModule & { dispose(): void };
`;

/** Every JSON table as one string literal, parsed at its first import. */
const jsonAsText = {
  name: 'json-as-text',
  setup(build) {
    // esbuild takes Go regular expressions: no u flag.
    build.onLoad({ filter: /\.json$/ }, async (args) => {
      const text = JSON.stringify(JSON.parse(await readFile(args.path, 'utf8')));
      return { contents: `export default JSON.parse(${JSON.stringify(text)});\n`, loader: 'js' };
    });
  },
};

/**
 * Module loading in the output, read from its syntax tree rather than its
 * text: esbuild names each inlined glob import in a comment and a string.
 */
export function runtimeImports(text) {
  const tree = ts.createSourceFile('bundle.mjs', text, ts.ScriptTarget.Latest, false, ts.ScriptKind.JS);
  const found = [];
  const visit = (node) => {
    if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier) {
      found.push(`import ${node.moduleSpecifier.getText(tree)}`);
    } else if (ts.isCallExpression(node)
      && (node.expression.kind === ts.SyntaxKind.ImportKeyword
        || (ts.isIdentifier(node.expression) && node.expression.text === 'require'))) {
      found.push(`${node.expression.getText(tree)}()`);
    }
    ts.forEachChild(node, visit);
  };
  visit(tree);
  return found;
}

/** Every table the resolver can load, as the bundle must carry it. */
async function tableFiles() {
  const history = (await readdir(resolve(ROOT, 'src/data/tz-history/2025c')))
    .filter((name) => /^\d{2}\.json$/u.test(name))
    .sort();
  return [
    'src/data/tz-lmt.json',
    'src/data/tz-history/2025c/excluded.json',
    ...history.map((name) => `src/data/tz-history/2025c/${name}`),
  ];
}

export async function buildLocalTimeBundle() {
  const banner = [
    '// Generated by scripts/build-compute-local-time.mjs from src/lib/time/localToUtc.ts. Do not edit.',
    '//',
    '// The site\'s local-time resolver for the compute API\'s function, with its tables inlined.',
    `// Bundled by esbuild ${esbuild.version}, platform node, format esm, target node22.`,
  ].join('\n');
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    absWorkingDir: ROOT,
    bundle: true,
    platform: 'node',
    format: 'iife',
    globalName: 'localTimeModule',
    target: 'node22',
    legalComments: 'inline',
    sourcemap: false,
    minify: false,
    write: false,
    metafile: true,
    plugins: [jsonAsText],
  });
  const [file] = result.outputFiles;
  // A fresh lexical module for each hosted request. None of the mutable zone
  // selection maps is shared, so overlapping prepares cannot erase one
  // another's pinned-history state. The source tables are public constants.
  const generated = file.text;
  const returned = '  return __toCommonJS(local_time_source_exports);';
  if (generated.split(returned).length !== 2) throw new Error('local-time module export changed; review the privacy wrapper');
  const disposal = `  return { ...__toCommonJS(local_time_source_exports), dispose() {
    offsetFormatters.clear();
    wallFormatters.clear();
    if (zoneHistories) zoneHistories.clear();
    if (zoneHistoryLoads) zoneHistoryLoads.clear();
  } };`;
  const text = `${banner}\n// Each request owns and disposes its zone-selection caches.\nexport function createLocalTimeModule() {\n${generated.replace(returned, disposal)}\nreturn localTimeModule;\n}\n`;
  const inputs = Object.keys(result.metafile.inputs).sort();
  const problems = [];
  for (const table of await tableFiles()) {
    if (!inputs.includes(table)) problems.push(`the bundle is missing ${table}`);
  }
  for (const source of ['src/lib/time/localToUtc.ts', 'src/lib/time/birthplace-clock.ts', 'src/lib/time/tz-history-load.ts', 'src/lib/time/zone-names.ts']) {
    if (!inputs.includes(source)) problems.push(`the bundle is missing ${source}`);
  }
  const imports = runtimeImports(text);
  if (imports.length) {
    problems.push(`the bundle loads ${imports.join(', ')} at run time; every module and table must be inlined`);
  }
  if (problems.length) throw new Error(`build-compute-local-time: ${problems.join('; ')}`);
  return {
    bytes: Buffer.from(text),
    types: Buffer.from(TYPES, 'utf8'),
    inputs,
    esbuild: esbuild.version,
  };
}

const invokedDirectly = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;
if (invokedDirectly) {
  const check = process.argv.includes('--check');
  const { bytes, types, inputs } = await buildLocalTimeBundle();
  const digest = createHash('sha256').update(bytes).digest('hex');
  if (check) {
    const stale = [];
    for (const [path, expected] of [[BUNDLE_PATH, bytes], [TYPES_PATH, types]]) {
      const current = await readFile(resolve(ROOT, path)).catch(() => null);
      if (current === null || !current.equals(expected)) stale.push(path);
    }
    if (stale.length) {
      console.error(`build-compute-local-time: ${stale.join(', ')} ${stale.length === 1 ? 'is' : 'are'} stale;`
        + ' run node scripts/build-compute-local-time.mjs and commit the result');
      process.exit(1);
    }
    console.log(`build-compute-local-time: up to date (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…)`);
  } else {
    await mkdir(dirname(resolve(ROOT, BUNDLE_PATH)), { recursive: true });
    await writeFile(resolve(ROOT, BUNDLE_PATH), bytes);
    await writeFile(resolve(ROOT, TYPES_PATH), types);
    console.log(`build-compute-local-time: wrote ${BUNDLE_PATH} (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…, ${inputs.length} inputs)`);
  }
}
