/**
 * Bundles the local-time resolver for the compute API's function.
 *
 *   node scripts/build-compute-local-time.mjs           # write api/_compute/local-time.mjs
 *   node scripts/build-compute-local-time.mjs --check   # fail on drift (CI)
 *
 * The resolver is @zodiacs/engine/geo, the one the birth chart calculator
 * reads local times with through src/lib/time/localToUtc.ts. It loads each
 * zone's history before 1970 on demand, from 16 files of the package, and the
 * map of zone names loads src/data/tz-names.json; the function's file trace
 * does not carry what is loaded on demand, so esbuild inlines all of it. The
 * bundle imports nothing at run time, which the build asserts.
 *
 * The bundle is an IIFE wrapped in createLocalTimeModule(), so each request
 * evaluates its own copy: no zone name, loaded history or formatter one
 * request leaves is seen by the next, and dispose() empties the engine's caches
 * when the request ends.
 *
 * Each JSON table is inlined as one string, parsed when it is first imported,
 * rather than as an object literal: V8 parses JSON text faster than the same
 * data as code, and tools that parse the repository's sources pay less.
 *
 * Source: src/lib/compute-api/local-time-source.ts. Output:
 * api/_compute/local-time.mjs and its declarations, local-time.d.mts. The
 * leading underscore keeps Vercel from deploying the directory as functions.
 */
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';
import * as esbuild from 'esbuild';
import ts from 'typescript';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const ENTRY = resolve(ROOT, 'src/lib/compute-api/local-time-source.ts');
export const BUNDLE_PATH = 'api/_compute/local-time.mjs';
export const TYPES_PATH = 'api/_compute/local-time.d.mts';

const TYPES = `// Generated by scripts/build-compute-local-time.mjs. Do not edit.
// Each call owns its resolver caches; a completed request must dispose them.
import type { LocalTimeModule } from '../../src/lib/compute-api/local-time.js';
export declare function createLocalTimeModule(): LocalTimeModule & { dispose(): void };
`;

/** Every JSON table as one string literal, parsed at its first import. */
const jsonAsText = {
  name: 'json-as-text',
  setup(build) {
    // esbuild takes Go regular expressions: no u flag.
    build.onLoad({ filter: /\.json$/ }, async (args) => {
      const text = JSON.stringify(JSON.parse(await readFile(args.path, 'utf8')));
      return { contents: `export default JSON.parse(${JSON.stringify(text)});\n`, loader: 'js' };
    });
  },
};

/**
 * Module loading in the output, read from its syntax tree rather than its
 * text: esbuild names each inlined glob import in a comment and a string.
 */
export function runtimeImports(text) {
  const tree = ts.createSourceFile('bundle.mjs', text, ts.ScriptTarget.Latest, false, ts.ScriptKind.JS);
  const found = [];
  const visit = (node) => {
    if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier) {
      found.push(`import ${node.moduleSpecifier.getText(tree)}`);
    } else if (ts.isCallExpression(node)
      && (node.expression.kind === ts.SyntaxKind.ImportKeyword
        || (ts.isIdentifier(node.expression) && node.expression.text === 'require'))) {
      found.push(`${node.expression.getText(tree)}()`);
    }
    ts.forEachChild(node, visit);
  };
  visit(tree);
  return found;
}

/** Every file the resolver can load, as the bundle must carry it: the zone names and the engine's 16 histories. */
async function loadedFiles() {
  const dist = 'node_modules/@zodiacs/engine/dist';
  const histories = (await readdir(resolve(ROOT, dist)))
    .filter((name) => /^tzdb-\d{4}[a-z]-\d{2}-[A-Z0-9]+\.js$/u.test(name))
    .sort();
  if (histories.length !== 16) throw new Error(`build-compute-local-time: the engine ships ${histories.length} history files, not 16`);
  return ['src/data/tz-names.json', ...histories.map((name) => `${dist}/${name}`)];
}

/**
 * The engine's mutable state in the bundle, as esbuild named it: the decoded
 * histories by zone, the pending history loads, and the offset formatters by
 * zone. Each must be found exactly once, or the wrapper is not emptying what
 * it means to.
 */
const ENGINE_CACHES = ['histories', 'loads', 'offsetFormatters'];
function engineCacheNames(text) {
  return ENGINE_CACHES.map((name) => {
    const found = [...text.matchAll(new RegExp(`\\bvar (${name}\\d*) = /\\* @__PURE__ \\*/ new Map\\(\\);`, 'gu'))].map((match) => match[1]);
    if (found.length !== 1) throw new Error(`build-compute-local-time: ${found.length} copies of the engine's ${name} map; review the privacy wrapper`);
    return found[0];
  });
}

export async function buildLocalTimeBundle() {
  const banner = [
    '// Generated by scripts/build-compute-local-time.mjs from @zodiacs/engine/geo. Do not edit.',
    '//',
    '// The engine\'s local-time resolver for the compute API\'s function, with the histories it loads inlined.',
    `// Bundled by esbuild ${esbuild.version}, platform node, format esm, target node22.`,
  ].join('\n');
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    absWorkingDir: ROOT,
    bundle: true,
    platform: 'node',
    format: 'iife',
    globalName: 'localTimeModule',
    target: 'node22',
    legalComments: 'inline',
    sourcemap: false,
    minify: false,
    write: false,
    metafile: true,
    plugins: [jsonAsText],
  });
  const [file] = result.outputFiles;
  // A fresh lexical module for each hosted request: none of the engine's maps
  // of zone names, histories or formatters is shared between requests. The
  // histories themselves are public constants.
  const generated = file.text;
  const returned = '  return __toCommonJS(local_time_source_exports);';
  if (generated.split(returned).length !== 2) throw new Error('local-time module export changed; review the privacy wrapper');
  const caches = engineCacheNames(generated);
  const disposal = `  return { ...__toCommonJS(local_time_source_exports), dispose() {
${caches.map((name) => `    ${name}.clear();`).join('\n')}
  } };`;
  const text = `${banner}\n// Each request owns and disposes the engine's zone caches.\nexport function createLocalTimeModule() {\n${generated.replace(returned, disposal)}\nreturn localTimeModule;\n}\n`;
  const inputs = Object.keys(result.metafile.inputs).sort();
  const problems = [];
  for (const loaded of await loadedFiles()) {
    if (!inputs.includes(loaded)) problems.push(`the bundle is missing ${loaded}`);
  }
  for (const source of ['src/lib/compute-api/local-time-source.ts', 'src/lib/time/zone-names.ts', 'node_modules/@zodiacs/engine/dist/geo.js']) {
    if (!inputs.includes(source)) problems.push(`the bundle is missing ${source}`);
  }
  for (const retired of ['src/lib/time/localToUtc.ts', 'src/lib/time/birthplace-clock.ts', 'src/lib/time/tz-history-load.ts']) {
    if (inputs.includes(retired)) problems.push(`the bundle still carries ${retired}`);
  }
  const imports = runtimeImports(text);
  if (imports.length) {
    problems.push(`the bundle loads ${imports.join(', ')} at run time; every module and table must be inlined`);
  }
  if (problems.length) throw new Error(`build-compute-local-time: ${problems.join('; ')}`);
  return {
    bytes: Buffer.from(text),
    types: Buffer.from(TYPES, 'utf8'),
    inputs,
    esbuild: esbuild.version,
  };
}

const invokedDirectly = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;
if (invokedDirectly) {
  const check = process.argv.includes('--check');
  const { bytes, types, inputs } = await buildLocalTimeBundle();
  const digest = createHash('sha256').update(bytes).digest('hex');
  if (check) {
    const stale = [];
    for (const [path, expected] of [[BUNDLE_PATH, bytes], [TYPES_PATH, types]]) {
      const current = await readFile(resolve(ROOT, path)).catch(() => null);
      if (current === null || !current.equals(expected)) stale.push(path);
    }
    if (stale.length) {
      console.error(`build-compute-local-time: ${stale.join(', ')} ${stale.length === 1 ? 'is' : 'are'} stale;`
        + ' run node scripts/build-compute-local-time.mjs and commit the result');
      process.exit(1);
    }
    console.log(`build-compute-local-time: up to date (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…)`);
  } else {
    await mkdir(dirname(resolve(ROOT, BUNDLE_PATH)), { recursive: true });
    await writeFile(resolve(ROOT, BUNDLE_PATH), bytes);
    await writeFile(resolve(ROOT, TYPES_PATH), types);
    console.log(`build-compute-local-time: wrote ${BUNDLE_PATH} (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…, ${inputs.length} inputs)`);
  }
}
