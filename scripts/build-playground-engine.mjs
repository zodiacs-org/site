/**
 * Bundles the compute API's calculations for the developer playground's
 * browser run.
 *
 *   node scripts/build-playground-engine.mjs           # write public/developers/playground/engine.mjs
 *   node scripts/build-playground-engine.mjs --check   # fail on drift (CI)
 *
 * Source: src/lib/compute-api/playground.ts, which answers a request body as
 * the hosted API's handler does, with the engine, astronomy-engine's ESM build
 * and the engine's local-time resolver with the 16 histories it loads before
 * 1970. node:crypto is aliased to src/lib/compute-api/playground-crypto.ts,
 * SHA-256 for the receipt digest. The output is a plain static file, as
 * public/precision-preview/ is: nothing in the Astro graph imports it, so no
 * page's chunks move because the playground exists, and the page loads it only
 * when someone asks to run a request in the browser. The build asserts that it
 * loads nothing at run time.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';
import * as esbuild from 'esbuild';
import { runtimeImports } from './build-compute-local-time.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const ENTRY = resolve(ROOT, 'src/lib/compute-api/playground.ts');
export const BUNDLE_PATH = 'public/developers/playground/engine.mjs';

async function packageVersion(name) {
  const text = await readFile(resolve(ROOT, 'node_modules', name, 'package.json'), 'utf8');
  return JSON.parse(text).version;
}

export async function buildPlaygroundEngineBundle() {
  const engine = await packageVersion('@zodiacs/engine');
  const astronomy = await packageVersion('astronomy-engine');
  const notice = await readFile(resolve(ROOT, 'node_modules/@zodiacs/engine/NOTICE'), 'utf8');
  if (!notice.includes('contains 32 values of Table S15') || !notice.includes('CC BY 4.0')) {
    throw new Error('engine NOTICE changed: review the playground bundle attribution');
  }
  const banner = [
    '// Generated by scripts/build-playground-engine.mjs from src/lib/compute-api/playground.ts. Do not edit.',
    '//',
    "// The compute API's calculations for the developer playground's browser run, with its dependencies inlined:",
    `// @zodiacs/engine ${engine} (MIT AND CC-BY-4.0; attribution copied from the archive's NOTICE below)`,
    `// and astronomy-engine ${astronomy} (MIT, Copyright (c) 2019-2023 Don Cross).`,
    `// Bundled by esbuild ${esbuild.version}, platform browser, format esm, target es2022, minified.`,
    '//',
    '// Engine NOTICE from the digest-pinned installed archive:',
    ...notice.trimEnd().split('\n').map((line) => line ? `// ${line}` : '//'),
  ].join('\n');
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    absWorkingDir: ROOT,
    bundle: true,
    platform: 'browser',
    format: 'esm',
    target: 'es2022',
    alias: { 'node:crypto': resolve(ROOT, 'src/lib/compute-api/playground-crypto.ts') },
    banner: { js: banner },
    legalComments: 'inline',
    sourcemap: false,
    minify: true,
    write: false,
    metafile: true,
  });
  const [file] = result.outputFiles;
  const text = file.text;
  const inputs = Object.keys(result.metafile.inputs).sort();
  const problems = [];
  for (const needed of [
    'src/lib/compute-api/playground.ts',
    'src/lib/compute-api/playground-crypto.ts',
    'src/lib/compute-api/endpoints.ts',
    'src/lib/compute-api/elections.ts',
    'src/lib/receipt-digest.ts',
    'src/data/tz-names.json',
  ]) {
    if (!inputs.includes(needed)) problems.push(`the bundle is missing ${needed}`);
  }
  if (!inputs.some((input) => input.startsWith('node_modules/astronomy-engine/esm/'))) {
    problems.push("the bundle does not carry astronomy-engine's ESM build");
  }
  if (!inputs.some((input) => input.startsWith('node_modules/@zodiacs/engine/dist/'))) {
    problems.push('the bundle does not carry @zodiacs/engine');
  }
  const histories = inputs.filter((input) => /^node_modules\/@zodiacs\/engine\/dist\/tzdb-\d{4}[a-z]-\d{2}-[A-Z0-9]+\.js$/u.test(input));
  if (histories.length !== 16) problems.push(`the bundle carries ${histories.length} of the engine's 16 zone histories`);
  const loads = runtimeImports(text);
  if (loads.length) problems.push(`the bundle loads modules at run time: ${loads.join(', ')}`);
  if (problems.length) throw new Error(`build-playground-engine: ${problems.join('; ')}`);
  return { bytes: Buffer.from(text), inputs };
}

const invokedDirectly = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;
if (invokedDirectly) {
  const check = process.argv.includes('--check');
  const { bytes, inputs } = await buildPlaygroundEngineBundle();
  const digest = createHash('sha256').update(bytes).digest('hex');
  if (check) {
    const current = await readFile(resolve(ROOT, BUNDLE_PATH)).catch(() => null);
    if (current === null || !current.equals(bytes)) {
      console.error(`build-playground-engine: ${BUNDLE_PATH} is stale; run node scripts/build-playground-engine.mjs and commit the result`);
      process.exit(1);
    }
    console.log(`build-playground-engine: up to date (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…)`);
  } else {
    await mkdir(dirname(resolve(ROOT, BUNDLE_PATH)), { recursive: true });
    await writeFile(resolve(ROOT, BUNDLE_PATH), bytes);
    console.log(`build-playground-engine: wrote ${BUNDLE_PATH} (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…, ${inputs.length} inputs)`);
  }
}
