/**
 * Bundles the compute API's handler, with the engine, for its Vercel function.
 *
 *   node scripts/build-compute-handler.mjs           # write api/_compute/compute.mjs
 *   node scripts/build-compute-handler.mjs --check   # fail on drift (CI)
 *
 * `@zodiacs/engine` imports named values from `astronomy-engine`, whose ESM
 * build sits in a package with no `"type": "module"`. On a Node that does not
 * detect module syntax, such as the one Vercel ran the function on at the
 * first deploy (2026-09-30), Node reads that file as CommonJS, finds no named
 * exports, and the handler fails to load: every compute endpoint answered
 * 500. The calendar function avoids the same trap with createRequire
 * (src/lib/engine/server-ephemeris.ts). Here esbuild bundles the handler, the
 * engine and astronomy-engine's ESM build into one module, so nothing is
 * resolved at run time but Node's own modules and `@vercel/firewall`, the
 * Firewall SDK the email, Aura and wallet functions already load. The build
 * asserts that.
 *
 * Source: src/lib/compute-api/handler.ts. Output: api/_compute/compute.mjs and
 * its declarations, compute.d.mts. The local-time resolver stays in its own
 * bundle, ./local-time.mjs (scripts/build-compute-local-time.mjs), passed in by
 * api/_compute/handler.ts. The leading underscore keeps Vercel from deploying
 * the directory as functions.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { builtinModules } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';
import * as esbuild from 'esbuild';
import { runtimeImports } from './build-compute-local-time.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const ENTRY = resolve(ROOT, 'src/lib/compute-api/handler.ts');
export const BUNDLE_PATH = 'api/_compute/compute.mjs';
export const TYPES_PATH = 'api/_compute/compute.d.mts';
/** What the bundle may load at run time: Node's own modules and the Firewall SDK. */
export const ALLOWED_RUNTIME_IMPORTS = ['@vercel/firewall'];

const TYPES = `// Generated by scripts/build-compute-handler.mjs. Do not edit.
// Declarations for the bundle beside this file; the source is src/lib/compute-api/handler.ts.
export { createComputeApiHandler } from '../../src/lib/compute-api/handler.js';
`;

async function packageVersion(name) {
  const text = await readFile(resolve(ROOT, 'node_modules', name, 'package.json'), 'utf8');
  return JSON.parse(text).version;
}

/** The module specifiers of the bundle's run-time imports, with Node's own modules removed. */
export function externalImports(text) {
  const builtins = new Set(builtinModules.flatMap((name) => [name, `node:${name}`]));
  return runtimeImports(text)
    .map((entry) => entry.replace(/^import ['"]|['"]$/gu, ''))
    .filter((specifier) => !builtins.has(specifier));
}

export async function buildComputeHandlerBundle() {
  const engine = await packageVersion('@zodiacs/engine');
  const astronomy = await packageVersion('astronomy-engine');
  const banner = [
    '// Generated by scripts/build-compute-handler.mjs from src/lib/compute-api/handler.ts. Do not edit.',
    '//',
    "// The compute API's handler for its Vercel function, with its dependencies inlined:",
    `// @zodiacs/engine ${engine} (MIT; its ΔT values are CC BY 4.0, attributed in vendor/README.md)`,
    `// and astronomy-engine ${astronomy} (MIT, Copyright (c) 2019-2023 Don Cross).`,
    `// Bundled by esbuild ${esbuild.version}, platform node, format esm, target node22.`,
  ].join('\n');
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    absWorkingDir: ROOT,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    external: ALLOWED_RUNTIME_IMPORTS,
    banner: { js: banner },
    legalComments: 'inline',
    sourcemap: false,
    minify: false,
    write: false,
    metafile: true,
  });
  const [file] = result.outputFiles;
  const text = file.text;
  const inputs = Object.keys(result.metafile.inputs).sort();
  const problems = [];
  for (const needed of ['src/lib/compute-api/handler.ts', 'src/lib/compute-api/endpoints.ts']) {
    if (!inputs.includes(needed)) problems.push(`the bundle is missing ${needed}`);
  }
  if (!inputs.some((input) => input.startsWith('node_modules/astronomy-engine/esm/'))) {
    problems.push("the bundle does not carry astronomy-engine's ESM build");
  }
  if (!inputs.some((input) => input.startsWith('node_modules/@zodiacs/engine/dist/'))) {
    problems.push('the bundle does not carry @zodiacs/engine');
  }
  const external = externalImports(text);
  const unexpected = external.filter((specifier) => !ALLOWED_RUNTIME_IMPORTS.includes(specifier));
  if (unexpected.length) {
    problems.push(`the bundle loads ${unexpected.join(', ')} at run time; only Node's modules and ${ALLOWED_RUNTIME_IMPORTS.join(', ')} may stay external`);
  }
  if (runtimeImports(text).some((entry) => !entry.startsWith('import '))) {
    problems.push('the bundle calls import() or require() at run time');
  }
  if (problems.length) throw new Error(`build-compute-handler: ${problems.join('; ')}`);
  return {
    bytes: Buffer.from(file.contents),
    types: Buffer.from(TYPES, 'utf8'),
    inputs,
    external,
  };
}

const invokedDirectly = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;
if (invokedDirectly) {
  const check = process.argv.includes('--check');
  const { bytes, types, inputs } = await buildComputeHandlerBundle();
  const digest = createHash('sha256').update(bytes).digest('hex');
  if (check) {
    const stale = [];
    for (const [path, expected] of [[BUNDLE_PATH, bytes], [TYPES_PATH, types]]) {
      const current = await readFile(resolve(ROOT, path)).catch(() => null);
      if (current === null || !current.equals(expected)) stale.push(path);
    }
    if (stale.length) {
      console.error(`build-compute-handler: ${stale.join(', ')} ${stale.length === 1 ? 'is' : 'are'} stale;`
        + ' run node scripts/build-compute-handler.mjs and commit the result');
      process.exit(1);
    }
    console.log(`build-compute-handler: up to date (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…)`);
  } else {
    await mkdir(dirname(resolve(ROOT, BUNDLE_PATH)), { recursive: true });
    await writeFile(resolve(ROOT, BUNDLE_PATH), bytes);
    await writeFile(resolve(ROOT, TYPES_PATH), types);
    console.log(`build-compute-handler: wrote ${BUNDLE_PATH} (${bytes.length} bytes, sha256 ${digest.slice(0, 12)}…, ${inputs.length} inputs)`);
  }
}
