// Writes one review sheet per locale for a native speaker: a sign's every
// horoscope period, the month, a full Moon and a new Moon page, and the
// zodiac dates explainer, each beside the English it stands in for where an
// English text exists. The reviewer checks natural phrasing, terms and
// register; nothing here is translated sentence by sentence.
//
//   npx vite-node --script scripts/locale-expansion/sample-sheet.ts            # all written locales
//   npx vite-node --script scripts/locale-expansion/sample-sheet.ts --check    # fail if a sheet is stale
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { HOROSCOPE_MODULES } from '../../src/lib/locale-expansion/horoscope/modules';
import { englishReading, localizedMonthlyReading, localizedPeriodReading, PERIOD_SURFACES } from '../../src/lib/locale-expansion/horoscope/engine';
import { expansionMonth } from '../../src/lib/locale-expansion/horoscope/month';
import { LUNATION_COPY } from '../../src/lib/locale-expansion/lunation/modules';
import { lunations } from '../../src/lib/locale-expansion/lunation/catalog';
import { zodiacDatesCopy } from '../../src/lib/locale-expansion/zodiac-dates/modules';
import { signBySlug, signName, SIGN_SLUGS } from '../../src/lib/signs';
import { solarHouse } from '../../src/lib/daily';
import type { ExpansionLocale } from '../../src/lib/locale-expansion/horoscope/types';

const check = process.argv.includes('--check');
const OUT = 'docs/visibility/samples';
const SIGN = 'leo';
const NAMES: Record<ExpansionLocale, string> = { es: 'Spanish', pt: 'Portuguese (Brazil)', fr: 'French', it: 'Italian', ru: 'Russian' };
const quote = (text: string) => text.split('\n').map((line) => `> ${line}`).join('\n');

function sheet(locale: ExpansionLocale): string {
  const mod = HOROSCOPE_MODULES[locale]!;
  const name = signName(signBySlug(SIGN), locale);
  const month = expansionMonth();
  const out: string[] = [];
  out.push(`# ${NAMES[locale]} sample sheet for native review`);
  out.push('');
  out.push(`Generated by \`scripts/locale-expansion/sample-sheet.ts\` from the same code the pages render. Sign shown: ${name}. Edition: ${month.month}. Nothing here is published: every family is held in \`src/data/locale-expansion-publication.json\`.`);
  out.push('');
  out.push('## For the reviewer');
  out.push('');
  out.push('Please mark each section and note any line you would rewrite (quote it, then your version):');
  out.push('');
  out.push('- [ ] Reads as written in this language, not translated');
  out.push('- [ ] Astrology terms are the ones local readers use');
  out.push('- [ ] Register is consistent (tu / vous / você / tu / ты) and warm, not salesy');
  out.push('- [ ] Grammar: agreement, contractions, elision, prepositions');
  out.push('- [ ] Dates and times read naturally');
  out.push('- [ ] Nothing reads as advice about money, health, betting or guarantees');
  out.push('');
  out.push('The English beside each text is the reading built from the same computed facts. The localized text is written from the facts, so it is not meant to match sentence by sentence.');
  out.push('');
  for (const surface of PERIOD_SURFACES) {
    const reading = localizedPeriodReading(mod, SIGN, surface);
    const english = englishReading(SIGN, surface);
    out.push(`## ${mod.chrome.title(name, { surface, from: reading.from, through: reading.through })}`);
    out.push('');
    out.push(`H1: ${mod.chrome.h1(name, { surface, from: reading.from, through: reading.through })}`);
    out.push('');
    out.push(`Description: ${mod.chrome.description(name, { surface, from: reading.from, through: reading.through })}`);
    out.push('');
    reading.passages.forEach((passage, index) => {
      out.push(passage.heading ? `**${passage.heading}**\n\n${passage.text}` : passage.text);
      out.push('');
      const en = english.passages[index];
      out.push(quote(`English: ${en.heading ? `${en.heading}. ` : ''}${en.text}`));
      out.push('');
    });
    out.push('- [ ] OK as is    - [ ] Needs changes (notes below)');
    out.push('');
  }
  const monthly = localizedMonthlyReading(mod, SIGN, month.transits);
  out.push(`## ${mod.chrome.title(name, { surface: 'monthly', from: `${month.month}-01`, through: `${month.month}-28`, month: month.month })}`);
  out.push('');
  for (const passage of monthly.passages) {
    out.push(passage.heading ? `**${passage.heading}**\n\n${passage.text}` : passage.text);
    out.push('');
  }
  out.push('- [ ] OK as is    - [ ] Needs changes (notes below)');
  out.push('');
  const lunation = LUNATION_COPY[locale];
  if (lunation) {
    for (const kind of ['full', 'new'] as const) {
      const next = lunations(kind).find((entry) => entry.date >= month.month) ?? lunations(kind).at(-1)!;
      const facts = next.facts;
      out.push(`## ${lunation.title(facts)}`);
      out.push('');
      out.push(lunation.lead(facts));
      out.push('');
      if (facts.eclipse) { out.push(lunation.eclipseNote(facts)); out.push(''); }
      for (const paragraph of lunation.meaning(facts)) { out.push(paragraph); out.push(''); }
      out.push(`**${lunation.signNotesHeading}**`);
      out.push('');
      for (const sign of SIGN_SLUGS.slice(0, 4)) out.push(`- ${lunation.signNote(sign, solarHouse(facts.sign, sign), facts)}`);
      out.push('');
      for (const { q, a } of lunation.faq(facts)) out.push(`- **${q}** ${a}`);
      out.push('');
      out.push('- [ ] OK as is    - [ ] Needs changes (notes below)');
      out.push('');
    }
  }
  try {
    const dates = zodiacDatesCopy(locale);
    out.push(`## ${dates.title(2026, 2027)}`);
    out.push('');
    out.push(dates.lede(2026, 2027));
    out.push('');
    for (const paragraph of dates.explainer) { out.push(paragraph); out.push(''); }
    out.push('- [ ] OK as is    - [ ] Needs changes (notes below)');
    out.push('');
  } catch { /* not written yet */ }
  out.push('## Reviewer notes');
  out.push('');
  out.push('Reviewer name and date:');
  out.push('');
  return `${out.join('\n').trimEnd()}\n`;
}

mkdirSync(OUT, { recursive: true });
let stale = 0;
for (const locale of Object.keys(HOROSCOPE_MODULES) as ExpansionLocale[]) {
  const file = `${OUT}/${locale}.md`;
  const text = sheet(locale);
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { console.error(`stale: ${file}`); stale += 1; }
  } else {
    writeFileSync(file, text);
    console.log(`wrote ${file}`);
  }
}
if (stale) process.exit(1);
