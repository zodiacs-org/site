#!/usr/bin/env node
/**
 * Copies the Astrologer bot's reading facts builder from the engine repository
 * (zodiacs-org/engine, bots/astrologer/facts/reading-facts.ts) into
 * src/engine-mcp/reading-facts.ts, for the reading_facts tool of the
 * /mcp/engine endpoint.
 *
 * The engine file imports the engine's source by relative path. The copy reads
 * the same functions from the packed @zodiacs/engine this site vendors, so each
 * import path is mapped to the package entry that exports it; an unmapped path
 * stops the copy. Nothing else in the file is changed.
 *
 *   node scripts/sync-reading-facts.mjs <engine checkout> [git ref, default HEAD]
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'bots/astrologer/facts/reading-facts.ts';
const TARGET = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'engine-mcp', 'reading-facts.ts');

/** Engine source module, as the engine file imports it, to the package entry that exports the same names. */
const ENTRIES = {
  'configured-aspects': '@zodiacs/engine',
  api: '@zodiacs/engine',
  aspects: '@zodiacs/engine',
  points: '@zodiacs/engine',
  returns: '@zodiacs/engine',
  signs: '@zodiacs/engine',
  types: '@zodiacs/engine',
  ephemeris: '@zodiacs/engine/internal',
  'geo/timezone': '@zodiacs/engine/geo',
  'techniques/moon-sign': '@zodiacs/engine/techniques',
  'techniques/dignities': '@zodiacs/engine/techniques',
};

const [checkout, ref = 'HEAD'] = process.argv.slice(2);
if (!checkout) {
  process.stderr.write('Usage: node scripts/sync-reading-facts.mjs <engine checkout> [git ref]\n');
  process.exit(2);
}
const git = (...args) => execFileSync('git', ['-C', checkout, ...args], { encoding: 'utf8' });
const commit = git('rev-parse', `${ref}^{commit}`).trim();
const source = git('show', `${commit}:${SOURCE}`);

const unmapped = [];
const body = source.replace(/from "\.\.\/\.\.\/\.\.\/src\/([a-z/-]+)\.js";/g, (_match, path) => {
  const entry = ENTRIES[path];
  if (!entry) unmapped.push(path);
  return `from "${entry}";`;
});
if (unmapped.length) {
  process.stderr.write(`No package entry is mapped for: ${unmapped.join(', ')}\n`);
  process.exit(1);
}
if (/from "\.\.?\//.test(body)) {
  process.stderr.write('The engine file imports a relative path this script does not map.\n');
  process.exit(1);
}

const digest = createHash('sha256').update(source).digest('hex');
const header = `// Generated by scripts/sync-reading-facts.mjs. Do not edit; rerun the script.
// Source: zodiacs-org/engine ${SOURCE} at ${commit}
// Source sha256: ${digest}
// Only the import paths differ from the source: they name the packed @zodiacs/engine entries.
`;
writeFileSync(TARGET, header + body);
process.stdout.write(`Wrote ${TARGET} from ${commit.slice(0, 12)}\n`);
