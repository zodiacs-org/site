/**
 * The account consent page (src/ai-tools/accounts/consent.*) as one HTML string
 * with its script and style inline and their CSP hashes. The hosted MCP
 * function serves it at /oauth/consent/ only while ZODIACS_ACCOUNTS_ENABLED=1;
 * nothing in the Astro site or the MCP runtime bundle imports it.
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const hash = (text) => `sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}`;

export async function buildAccountsConsent(check = false) {
  const result = await build({ absWorkingDir: fileURLToPath(root), entryPoints: ['src/ai-tools/accounts/consent.ts'], bundle: true, write: false,
    format: 'iife', platform: 'browser', target: 'es2022', minify: true, legalComments: 'inline' });
  const js = result.outputFiles[0].text.trim().replace(/<\/script/gi, '<\\/script');
  const css = (await readFile(new URL('src/ai-tools/accounts/consent.css', root), 'utf8')).trim();
  const template = await readFile(new URL('src/ai-tools/accounts/consent.html', root), 'utf8');
  if (!template.includes('/*CONSENT_JS*/') || !template.includes('/*CONSENT_CSS*/')) throw new Error('The consent template lost its placeholders.');
  const licenses = (await Promise.all(['node_modules/@supabase/supabase-js/LICENSE', 'public/fonts/OFL-instrument-sans.txt', 'public/fonts/OFL-eb-garamond.txt']
    .map(file => readFile(new URL(file, root), 'utf8').catch(() => '')))).filter(Boolean).join('\n\n').replace(/-->/g, '-- >');
  const html = template.trim().replace('/*CONSENT_CSS*/', () => css).replace('/*CONSENT_JS*/', () => js)
    .replace('<body>', () => `<body><!-- Bundled third-party notices\n${licenses}\n-->`);
  if (Buffer.byteLength(html) > 400_000) throw new Error('The consent page exceeds its 400 KB budget.');
  const content = '// Generated by scripts/build-accounts-consent.mjs via ai:build. Do not edit.\n'
    + `export const CONSENT_HTML = ${JSON.stringify(html)};\n`
    + `export const CONSENT_SCRIPT_HASH = ${JSON.stringify(hash(js))};\n`
    + `export const CONSENT_STYLE_HASH = ${JSON.stringify(hash(css))};\n`;
  const output = new URL('integrations/generated/accounts-consent.mjs', root);
  if (check) { if (await readFile(output, 'utf8').catch(() => '') !== content) throw new Error('The account consent page is stale; run ai:build'); }
  else { await mkdir(new URL('integrations/generated/', root), { recursive: true }); await writeFile(output, content); }
  console.log(`${check ? 'Verified' : 'Built'} the account consent page (${Buffer.byteLength(html)} bytes)`);
  return html;
}
