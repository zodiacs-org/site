/** MCP App for the five coverage tools: sign icons and fonts inline, full-size public art from zodiacs.org, no reading data. */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const SIGNS = ['aries', 'taurus', 'gemini', 'cancer', 'leo', 'virgo', 'libra', 'scorpio', 'sagittarius', 'capricorn', 'aquarius', 'pisces'];
const ANIMALS = ['rat', 'ox', 'tiger', 'rabbit', 'dragon', 'snake', 'horse', 'goat', 'monkey', 'rooster', 'dog', 'pig'];
const ART_PIECES = ['milestones-hero', 'sky-calendar-hero'];

/**
 * The panel offered while ZODIACS_SKY_EVENTS_ENABLED=1 is the same app with
 * src/ai-tools/readings-panel/views-sky-events.tsx in place of ./views: its
 * birth chart lists the lunar nodes. The panel built without it keeps its bytes.
 */
const skyEventsViews = {
  name: 'readings-sky-events-views',
  setup(builder) {
    const views = fileURLToPath(new URL('src/ai-tools/readings-panel/views-sky-events.tsx', root));
    builder.onResolve({ filter: /^\.\/views$/ }, (args) => (args.importer.endsWith('/readings-panel/app.tsx') ? { path: views } : undefined));
  },
};

async function panelHtml(plugins) {
  const inline = async (path) => `data:image/webp;base64,` + (await readFile(new URL(path, root))).toString('base64');
  const icons = Object.fromEntries(await Promise.all(SIGNS.map(async (slug) => [slug, await inline(`public/assets/zodiac-icons/128/${slug}.webp`)])));
  const art = Object.fromEntries([
    ...SIGNS.flatMap((slug) => [
      [slug, `https://zodiacs.org/assets/sign-art/${slug}-1200.avif`],
      [`${slug}-light`, `https://zodiacs.org/assets/card-art/${slug}-light-720.webp`],
    ]),
    ...ART_PIECES.flatMap((key) => [
      [key, `https://zodiacs.org/assets/card-art/${key}-1200.webp`],
      [`${key}-light`, `https://zodiacs.org/assets/card-art/${key}-light-1200.webp`],
    ]),
    ...ANIMALS.map((animal) => [`chinese-${animal}`, `https://zodiacs.org/assets/art/chinese-zodiac/${animal}-1280.webp`]),
  ]);
  const result = await build({ absWorkingDir: fileURLToPath(root), entryPoints: ['src/ai-tools/readings-panel/app.tsx'], bundle: true, write: false, outdir: 'out', format: 'iife', platform: 'browser', target: 'es2022', minify: true, legalComments: 'inline', jsx: 'automatic', jsxImportSource: 'preact', define: { READINGS_ICONS: JSON.stringify(icons), CARD_ART: JSON.stringify(art), 'process.env.NODE_ENV': '"production"' }, ...(plugins ? { plugins } : {}) });
  const js = result.outputFiles.find(file => file.path.endsWith('.js')).text.replace(/<\/script/gi, '<\\/script');
  let css = result.outputFiles.find(file => file.path.endsWith('.css')).text;
  for (const [family, file, weight, style] of [['Instrument Sans', 'instrument-sans-latin-wght-normal.woff2', '100 900', 'normal'], ['EB Garamond', 'eb-garamond-latin-400-normal.woff2', '400', 'normal'], ['EB Garamond', 'eb-garamond-latin-500-normal.woff2', '500', 'normal'], ['EB Garamond', 'eb-garamond-latin-400-italic.woff2', '400', 'italic'], ['JetBrains Mono', 'jetbrains-mono-latin-wght-normal.woff2', '100 800', 'normal']]) {
    css += `@font-face{font-family:'${family}';src:url(data:font/woff2;base64,${(await readFile(new URL(`public/fonts/${file}`, root))).toString('base64')}) format('woff2');font-weight:${weight};font-style:${style};font-display:swap;}`;
  }
  const licenses = (await Promise.all(['public/fonts/OFL-instrument-sans.txt', 'public/fonts/OFL-eb-garamond.txt', 'public/fonts/OFL-jetbrains-mono.txt', 'node_modules/preact/LICENSE'].map(file => readFile(new URL(file, root), 'utf8')))).join('\n\n').replace(/-->/g, '-- >');
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex"><title>Readings · Zodiacs</title><style>${css}</style></head><body><!-- Bundled third-party notices\n${licenses}\n--><div id="readings"></div><noscript>Enable JavaScript to see the reading here, or visit zodiacs.org.</noscript><script>${js}</script></body></html>`;
  if (Buffer.byteLength(JSON.stringify(html)) > 700_000) throw new Error('The readings panel exceeds its 700 KB resource budget.');
  return html;
}

async function writeOrCheck(file, content, check, stale) {
  const output = new URL(`integrations/generated/${file}`, root);
  if (check) { if (await readFile(output, 'utf8').catch(() => '') !== content) throw new Error(stale); }
  else { await mkdir(new URL('integrations/generated/', root), { recursive: true }); await writeFile(output, content); }
}

export async function buildReadingsPanel(check = false) {
  const html = await panelHtml(null);
  const content = '// Generated by scripts/build-readings-panel.mjs via ai:build. Do not edit.\nexport const READINGS_HTML = ' + JSON.stringify(html) + ';\n';
  await writeOrCheck('readings.mjs', content, check, 'The readings panel is stale; run ai:build');
  console.log(`${check ? 'Verified' : 'Built'} the readings panel (${Buffer.byteLength(html)} bytes, owned public art)`);
  return html;
}

/** The readings panel offered while ZODIACS_SKY_EVENTS_ENABLED=1, whose birth chart lists the lunar nodes. */
export async function buildReadingsSkyEventsPanel(check = false) {
  const html = await panelHtml([skyEventsViews]);
  const content = '// Generated by scripts/build-readings-panel.mjs via ai:build. Do not edit.\n// The readings panel offered while ZODIACS_SKY_EVENTS_ENABLED=1: its birth chart lists the lunar nodes.\nexport const READINGS_SKY_EVENTS_HTML = ' + JSON.stringify(html) + ';\n';
  await writeOrCheck('readings-sky-events.mjs', content, check, 'The sky events readings panel is stale; run ai:build');
  console.log(`${check ? 'Verified' : 'Built'} the readings panel with the lunar nodes (${Buffer.byteLength(html)} bytes, owned public art)`);
  return html;
}
