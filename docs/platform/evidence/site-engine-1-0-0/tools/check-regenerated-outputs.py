#!/usr/bin/env python3
"""Recheck the retained regeneration record against its immutable base.

For each output the record lists, the committed file must be the base's bytes
where the record keeps them (the output regenerated identically, or differed
only by a restamped date or by last-bit arm64 arithmetic, FINDINGS F-82), and
otherwise the regenerated bytes with exactly the recorded JSON differences.
"""
from collections import Counter
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[5]
REPORT = Path(__file__).resolve().parents[1] / 'regenerated-outputs.json'


def differences(before, after, path='', counts=None):
    if counts is None:
        counts = Counter()
    if isinstance(before, dict) and isinstance(after, dict):
        for key in before.keys() | after.keys():
            child = f'{path}.{key}'
            if key not in before or key not in after:
                counts[child] += 1
            else:
                differences(before[key], after[key], child, counts)
    elif isinstance(before, list) and isinstance(after, list):
        for index in range(max(len(before), len(after))):
            if index >= len(before) or index >= len(after):
                counts[f'{path}[]'] += 1
            else:
                differences(before[index], after[index], f'{path}[]', counts)
    elif before != after:
        counts[path] += 1
    return dict(counts)


report = json.loads(REPORT.read_text())
kept_base = set(report['summary']['baseBytesKept'])
for item in report['files']:
    prior = subprocess.check_output(
        ['git', 'show', f"{report['base']}:{item['path']}"], cwd=ROOT)
    committed = (ROOT / item['path']).read_bytes()
    if hashlib.sha256(prior).hexdigest() != item['baseSha256']:
        raise SystemExit(f"FAIL: {item['path']}: base digest differs from its record")
    if item['sameBytes'] or item['path'] in kept_base:
        if committed != prior:
            raise SystemExit(f"FAIL: {item['path']}: expected the base bytes")
    else:
        if hashlib.sha256(committed).hexdigest() != item['regeneratedSha256'] \
                or differences(json.loads(prior), json.loads(committed)) != item['differences']:
            raise SystemExit(f"FAIL: {item['path']}: regenerated bytes differ from the record")
print(f"PASS: {len(report['files'])} regenerated outputs match the record "
      f"({sum(f['sameBytes'] for f in report['files'])} identical, {len(kept_base)} base bytes kept, "
      f"{len(report['summary']['kept'])} regenerated)")
