#!/usr/bin/env python3
"""Scores the runs in runs/ against questions.json and writes RESULTS.md (rates) and MISSES.md (every miss).

A run is right when the first tool the model called is the expected tool or one of the other first calls
questions.json accepts for that question; for an expected 'none', when it called no tool. Anything else is a miss:
'wrong tool' when it called another tool, 'no tool' when it called none and one was expected, 'called a tool' when
none was expected. Run: python3 tools/score.py"""
import json, os, glob, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
questions = {q['id']: q for q in json.load(open(os.path.join(ROOT, 'questions.json')))}
SETS = {'live': 'Live server (0.6.6)', 'pr971': 'PR 971 head (2d1f90f01)', 'branch': 'This branch', 'branch-no-instructions': 'This branch, connector instructions withheld'}
runs = {}
for path in sorted(glob.glob(os.path.join(ROOT, 'runs', '*.jsonl'))):
    tool_set, model = os.path.basename(path)[:-6].split('.', 1)
    runs[(tool_set, model)] = {row['id']: row for row in map(json.loads, open(path))}

def verdict(question, row):
    first = row['calls'][0]['name'] if row['calls'] else 'none'
    if first in question['accept']: return first, None
    if question['expected'] == 'none': return first, 'called a tool'
    return first, 'no tool' if first == 'none' else 'wrong tool'

results, misses = ['# Results', '', 'Generated by `tools/score.py` from `runs/*.jsonl`. Do not edit by hand.', ''], []
results += ['| Tool descriptions | Model | Asked | Right | Rate | Wrong tool | No tool | Called a tool when none was expected |', '|---|---|---|---|---|---|---|---|']
per_tool = collections.defaultdict(dict)
for (tool_set, model), rows in sorted(runs.items(), key=lambda item: (list(SETS).index(item[0][0]), item[0][1])):
    counts = collections.Counter()
    for qid, question in questions.items():
        if qid not in rows: counts['missing'] += 1; continue
        first, miss = verdict(question, rows[qid])
        counts[miss or 'right'] += 1
        tally = per_tool[question['expected']].setdefault((tool_set, model), [0, 0]); tally[1] += 1; tally[0] += miss is None
        if miss: misses.append((tool_set, model, qid, question, first, miss, rows[qid]))
    asked = len(questions) - counts['missing']
    results.append(f"| {SETS[tool_set]} | {model} | {asked} | {counts['right']} | {100 * counts['right'] / max(asked, 1):.1f}% | {counts['wrong tool']} | {counts['no tool']} | {counts['called a tool']} |")
columns = sorted(runs, key=lambda key: (list(SETS).index(key[0]), key[1]))
results += ['', '## Right answers by expected tool', '', '| Expected | ' + ' | '.join(f'{s} / {m}' for s, m in columns) + ' |', '|---|' + '---|' * len(columns)]
for tool in sorted(per_tool, key=lambda t: (t == 'none', t)):
    results.append(f'| {tool} | ' + ' | '.join('{}/{}'.format(*per_tool[tool].get(column, [0, 0])) for column in columns) + ' |')
open(os.path.join(ROOT, 'RESULTS.md'), 'w').write('\n'.join(results) + '\n')

out = ['# Miss log', '', 'Generated by `tools/score.py` from `runs/*.jsonl`. Every run where the first tool call was not an accepted one.', '']
for tool_set in SETS:
    for model in sorted({m for s, m in runs if s == tool_set}):
        mine = [m for m in misses if m[0] == tool_set and m[1] == model]
        out += [f'## {SETS[tool_set]}, {model}: {len(mine)} misses', '']
        if not mine: out += ['None.', '']; continue
        out += ['| Id | Question | Expected | Chosen | Kind | What it said or sent |', '|---|---|---|---|---|---|']
        for _, _, qid, question, first, miss, row in mine:
            detail = json.dumps(row['calls'][0]['arguments'], ensure_ascii=False) if row['calls'] else row.get('text', '')
            detail = detail.replace('\n', ' ').replace('|', '/')[:220]
            expected = ' or '.join(question['accept'])
            out.append(f"| {qid} | {question['question'].replace('|', '/')} | {expected} | {first} | {miss} | {detail} |")
        out.append('')
open(os.path.join(ROOT, 'MISSES.md'), 'w').write('\n'.join(out) + '\n')
json.dump([{'toolSet': s, 'model': m, 'id': qid, 'question': q['question'], 'expected': q['expected'], 'accept': q['accept'], 'chosen': first, 'kind': miss,
            'allCalls': [c['name'] for c in row['calls']]} for s, m, qid, q, first, miss, row in misses], open(os.path.join(ROOT, 'misses.json'), 'w'), indent=1, ensure_ascii=False)
print('\n'.join(results))
