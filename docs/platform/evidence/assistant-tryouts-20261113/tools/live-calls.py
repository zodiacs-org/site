#!/usr/bin/env python3
"""Writes LIVE-CALLS.md: how the live connector answered the calls the live runs sent on to it. Run: python3 tools/live-calls.py"""
import json, os, glob, collections
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
replay_path = os.path.join(ROOT, 'runs', 'live-replay.jsonl')
replay = {(r['id'], r['model'], r['index']): r['live'] for r in map(json.loads, open(replay_path))} if os.path.exists(replay_path) else {}
def kind(live):
    if not live: return 'not sent'
    if 'failed' in live: return 'network failure'
    if live.get('status') == 429 or live.get('error') == 'rate-limited': return 'rate-limited by the live server'
    if live.get('ok') is True and not live.get('isError'): return 'answered'
    return f"refused or error ({live.get('error')})"
lines = ['# Live connector answers', '', 'Generated by `tools/live-calls.py`. The live runs sent every call the model made in its first turn on to',
         '`https://zodiacs.org/mcp` (read-only). "At first" is that answer; "after the replay" counts the answer `tools/replay-live.py`', 'got when it sent a rate-limited or dropped call again, slowly.', '']
other = []
for path in sorted(glob.glob(os.path.join(ROOT, 'runs', 'live.*.jsonl'))):
    first, final = collections.Counter(), collections.Counter()
    for row in map(json.loads, open(path)):
        for index, call in enumerate(row['calls']):
            live = call.get('live'); first[kind(live)] += 1
            again = replay.get((row['id'], row['model'], index), live); final[kind(again)] += 1
            if kind(again).startswith('refused'): other.append((row['model'], row['id'], call['name'], again.get('error'), row['question']))
    model = os.path.basename(path)[5:-6]
    lines += [f'## {model}', '', '| Answer | At first | After the replay |', '|---|---|---|']
    for key in sorted(set(first) | set(final)): lines.append(f'| {key} | {first[key]} | {final[key]} |')
    lines.append('')
lines += ['## Calls the live server refused or could not run', '', '| Model | Id | Tool | Error code | Question |', '|---|---|---|---|---|']
lines += [f'| {m} | {i} | {t} | {e} | {q} |' for m, i, t, e, q in other]
open(os.path.join(ROOT, 'LIVE-CALLS.md'), 'w').write('\n'.join(lines) + '\n')
print('\n'.join(lines[:30]))
