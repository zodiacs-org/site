#!/usr/bin/env python3
"""Scores breaker-join/runs/*.jsonl and writes RESULTS.md, MISSES.md and misses.json.
fresh50* runs are scored against breaker/questions.json (the fix-round breaker's 50, unchanged);
probes* runs against breaker-join/probes.json. Right = the first tool called is one the question accepts;
for 'none', no tool was called. Run: python3 score.py"""
import json, os, glob, collections
HERE = os.path.dirname(os.path.abspath(__file__))
SETS = {'fresh50': json.load(open(os.path.join(HERE, '..', 'breaker', 'questions.json'))), 'probes': json.load(open(os.path.join(HERE, 'probes.json')))}
TITLE = {'fresh50': 'The fresh 50', 'probes': 'The 18 probes'}
out = ['# Join-round breaker results', '', 'Generated by `score.py` from `runs/*.jsonl`. Do not edit by hand.']
misses, cats = [], collections.defaultdict(dict)
for key, qs in SETS.items():
    questions = {q['id']: q for q in qs}
    out += ['', f'## {TITLE[key]}', '', '| Run | Model | Asked | Right | Rate | Wrong tool | No tool | Called a tool when none was expected |', '|---|---|---|---|---|---|---|---|']
    for path in sorted(glob.glob(os.path.join(HERE, 'runs', key + '*.jsonl'))):
        run, model = os.path.basename(path)[:-6].split('.', 1)
        label = 'Connector instructions withheld' if run.endswith('-no-instructions') else 'With the connector instructions'
        rows = {r['id']: r for r in map(json.loads, open(path))}
        c = collections.Counter()
        for qid, q in questions.items():
            if qid not in rows: c['missing'] += 1; continue
            first = rows[qid]['calls'][0]['name'] if rows[qid]['calls'] else 'none'
            kind = None if first in q['accept'] else 'called a tool' if q['expected'] == 'none' else 'no tool' if first == 'none' else 'wrong tool'
            c[kind or 'right'] += 1
            t = cats[(key, q['category'])].setdefault((label, model), [0, 0]); t[1] += 1; t[0] += kind is None
            if kind: misses.append((key, label, model, qid, q, first, kind, rows[qid]))
        asked = len(questions) - c['missing']
        out.append(f"| {label} | {model} | {asked} | {c['right']} | {100 * c['right'] / max(asked, 1):.0f}% | {c['wrong tool']} | {c['no tool']} | {c['called a tool']} |")
cols = sorted({k for v in cats.values() for k in v})
out += ['', '## By category (right of asked)', '', '| Set | Category | ' + ' | '.join(f'{l.split()[0] if l.startswith("With") else "Withheld"}, {m}' for l, m in cols) + ' |', '|---|---|' + '---|' * len(cols)]
for (key, cat), v in cats.items():
    out.append(f'| {key} | {cat} | ' + ' | '.join(f'{v[k][0]} of {v[k][1]}' if k in v else '' for k in cols) + ' |')
open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(out) + '\n')
m = ['# Join-round breaker miss log', '', 'Generated by `score.py`. Every run where the first call was not an accepted one.', '',
     '| Set | Run | Model | Id | Category | Question | Expected | Chosen | Kind | What it said or sent |', '|---|---|---|---|---|---|---|---|---|---|']
for key, label, model, qid, q, first, kind, row in misses:
    detail = (json.dumps(row['calls'][0]['arguments'], ensure_ascii=False) if row['calls'] else row.get('text', '')).replace('\n', ' ').replace('|', '/')[:260]
    m.append(f"| {key} | {label} | {model} | {qid} | {q['category']} | {q['question']} | {' or '.join(q['accept'])} | {first} | {kind} | {detail} |")
open(os.path.join(HERE, 'MISSES.md'), 'w').write('\n'.join(m) + '\n')
json.dump([{'set': s, 'run': r, 'model': mo, 'id': i, 'category': q['category'], 'question': q['question'], 'accept': q['accept'], 'chosen': f, 'kind': k, 'allCalls': [c['name'] for c in row['calls']]}
           for s, r, mo, i, q, f, k, row in misses], open(os.path.join(HERE, 'misses.json'), 'w'), indent=1, ensure_ascii=False)
print('\n'.join(out)); print(); print('\n'.join(m[4:]))
