#!/usr/bin/env python3
"""Scores breaker/runs/*.jsonl against breaker/questions.json and writes RESULTS.md and MISSES.md.
Right = the first tool the model called is one the question accepts; for 'none', it called no tool.
A second, lenient count is given for the 'ask first' questions only: there it also accepts the tool the
request would get once the other person's agreement is known, which is how the builder's 200 scored them.
Run: python3 score.py"""
import json, os, glob, collections
HERE = os.path.dirname(os.path.abspath(__file__))
questions = {q['id']: q for q in json.load(open(os.path.join(HERE, 'questions.json')))}
LENIENT = {'f24': ['get_natal_chart', 'find_birthplace'], 'f25': ['get_compatibility'], 'f26': ['get_life_milestones']}
LABEL = {'fresh50': 'With the connector instructions', 'fresh50-no-instructions': 'Connector instructions withheld'}
out, misses = ['# Breaker results: the fresh 50', '', 'Generated by `score.py` from `runs/*.jsonl`. Do not edit by hand.', '',
       '| Run | Model | Asked | Right | Rate | Wrong tool | No tool | Called a tool when none was expected | Right if "ask first" may also call the tool |', '|---|---|---|---|---|---|---|---|---|'], []
cats = collections.defaultdict(dict)
for path in sorted(glob.glob(os.path.join(HERE, 'runs', '*.jsonl'))):
    run, model = os.path.basename(path)[:-6].split('.', 1)
    rows = {r['id']: r for r in map(json.loads, open(path))}
    c = collections.Counter(); lenient = 0
    for qid, q in questions.items():
        if qid not in rows: c['missing'] += 1; continue
        first = rows[qid]['calls'][0]['name'] if rows[qid]['calls'] else 'none'
        kind = None if first in q['accept'] else 'called a tool' if q['expected'] == 'none' else 'no tool' if first == 'none' else 'wrong tool'
        c[kind or 'right'] += 1; lenient += kind is None or first in LENIENT.get(qid, [])
        t = cats[q['category']].setdefault((run, model), [0, 0]); t[1] += 1; t[0] += kind is None
        if kind: misses.append((run, model, qid, q, first, kind, rows[qid]))
    asked = len(questions) - c['missing']
    out.append(f"| {LABEL[run]} | {model} | {asked} | {c['right']} | {100 * c['right'] / max(asked, 1):.0f}% | {c['wrong tool']} | {c['no tool']} | {c['called a tool']} | {lenient} ({100 * lenient / max(asked, 1):.0f}%) |")
open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(out) + '\n')
m = ['# Breaker miss log: the fresh 50', '', 'Generated by `score.py`. Every run where the first call was not an accepted one.', '',
     '| Run | Model | Id | Category | Question | Expected | Chosen | Kind | What it said or sent |', '|---|---|---|---|---|---|---|---|---|']
for run, model, qid, q, first, kind, row in misses:
    detail = (json.dumps(row['calls'][0]['arguments'], ensure_ascii=False) if row['calls'] else row.get('text', '')).replace('\n', ' ').replace('|', '/')[:260]
    m.append(f"| {LABEL[run]} | {model} | {qid} | {q['category']} | {q['question']} | {' or '.join(q['accept'])} | {first} | {kind} | {detail} |")
open(os.path.join(HERE, 'MISSES.md'), 'w').write('\n'.join(m) + '\n')
json.dump([{'run': r, 'model': mo, 'id': i, 'category': q['category'], 'question': q['question'], 'accept': q['accept'], 'chosen': f, 'kind': k, 'allCalls': [c['name'] for c in row['calls']]}
           for r, mo, i, q, f, k, row in misses], open(os.path.join(HERE, 'misses.json'), 'w'), indent=1, ensure_ascii=False)
print('\n'.join(out)); print(); print('\n'.join(m[4:]))
